import json
import pytest

from mocap_app.miobject import (
    MiobjectError,
    _select_keyframes,
    export_miobject,
)
from mocap_app.retarget import calculate_pose_controls


def standing_pose():
    world = [[0.0, 0.0, 0.0, 1.0, 1.0] for _ in range(33)]
    points = {
        0: (0.0, -1.9, -0.1),
        7: (-0.12, -1.75, 0.0),
        8: (0.12, -1.75, 0.0),
        11: (-0.25, -1.25, 0.0),
        12: (0.25, -1.25, 0.0),
        13: (-0.28, -0.85, 0.0),
        14: (0.28, -0.85, 0.0),
        15: (-0.30, -0.45, 0.0),
        16: (0.30, -0.45, 0.0),
        23: (-0.16, 0.0, 0.0),
        24: (0.16, 0.0, 0.0),
        25: (-0.17, 0.75, 0.0),
        26: (0.17, 0.75, 0.0),
        27: (-0.17, 1.5, 0.0),
        28: (0.17, 1.5, 0.0),
    }
    for index, point in points.items():
        world[index] = [*point, 1.0, 1.0]
    return {"world": world, "image": []}


def make_template(path):
    parts = {
        "body": {
            "ROT_X": 0.0,
            "ROT_Y": 0.0,
            "ROT_Z": 0.0,
            "BEND_ANGLE_X": -4.4,
            "BEND_ANGLE_Z": 20.4,
        },
        "head": {"ROT_X": 0.0, "ROT_Y": 0.0, "ROT_Z": 0.0},
        "left_arm": {
            "ROT_X": 0.0, "ROT_Y": 0.0, "ROT_Z": 0.0,
            "BEND_ANGLE_X": 0.0, "POS_Z": -0.53,
        },
        "right_arm": {
            "ROT_X": 0.0, "ROT_Y": 0.0, "ROT_Z": 0.0,
            "BEND_ANGLE_X": 0.0, "POS_Z": -0.43,
        },
        "left_leg": {
            "ROT_X": 0.0, "ROT_Y": 0.0, "ROT_Z": 0.0,
            "BEND_ANGLE_X": 0.0,
        },
        "right_leg": {
            "ROT_X": 0.0, "ROT_Y": 0.0, "ROT_Z": 0.0,
            "BEND_ANGLE_X": 0.0,
        },
    }
    timelines = [
        {
            "id": "folder",
            "type": "folder",
            "keyframes": {"0": {"ROT_Y": 80}, "30": {"ROT_Y": 120}},
        },
        {
            "id": "character",
            "type": "char",
            "default_values": {"POS_X": 12.0, "POS_Y": 24.0, "POS_Z": 3.0},
            "keyframes": {
                "0": {"POS_X": 12.0, "POS_Y": 24.0, "POS_Z": 3.0, "ROT_Z": 0.0},
                "30": {"POS_X": 80.0, "POS_Y": 90.0, "POS_Z": 45.0, "ROT_Z": 90.0},
            },
        },
    ]
    part_ids = {part: f"part-{index}" for index, part in enumerate(parts)}
    for part, values in parts.items():
        parent = (
            part_ids["body"]
            if part in {"head", "left_arm", "right_arm"}
            else "character"
        )
        first = dict(values)
        if part == "head":
            first["TEXTURE_OBJ"] = "GREGOR_HEAD_TEXTURE"
        timelines.append({
            "id": part_ids[part],
            "type": "bodypart",
            "model_part_name": part,
            "parent": parent,
            "keyframes": {"0": first},
        })
    timelines.append({
        "id": "hat",
        "type": "bodypart",
        "model_part_name": "hat",
        "keyframes": {},
    })
    template = {
        "format": 35,
        "created_in": "2.0.2 Community Build 1.0.0",
        "templates": [{
            "model": {
                "name": "human",
                "state": {"variant": "steve", "type": "slim"},
            }
        }],
        "timelines": timelines,
        "resources": [],
    }
    path.write_text(json.dumps(template), encoding="utf-8")


def test_direct_retarget_outputs_all_six_parts_and_keeps_rest_pose():
    pose = standing_pose()
    controls = calculate_pose_controls(pose)
    assert set(controls) == {
        "body", "head", "left_arm", "right_arm", "left_leg", "right_leg"
    }
    for part in ("left_leg", "right_leg"):
        assert abs(controls[part]["ROT_X"]) < 0.01
        assert abs(controls[part]["ROT_Z"]) < 1.0
        assert abs(controls[part]["BEND_ANGLE_X"]) < 0.01


def test_left_and_right_legs_follow_their_own_captured_segments():
    neutral = standing_pose()
    moved = standing_pose()
    # A forward/backward alternating step, with knee flexion on both sides.
    moved["world"][25][0] -= 0.16
    moved["world"][27][0] -= 0.30
    moved["world"][26][0] += 0.14
    moved["world"][28][0] += 0.27
    moved["world"][27][1] += 0.12
    moved["world"][28][1] -= 0.08

    controls = calculate_pose_controls(moved)
    assert abs(controls["left_leg"]["ROT_Z"]) > 5.0
    assert abs(controls["right_leg"]["ROT_Z"]) > 5.0
    assert controls["left_leg"]["BEND_ANGLE_X"] > 0.0
    assert controls["right_leg"]["BEND_ANGLE_X"] > 0.0
    # No global character control is ever generated by the pose mapper.
    assert "root" not in controls
    assert "char" not in controls


def test_arm_segments_and_elbow_bends_are_mapped_independently():
    pose = standing_pose()
    pose["world"][13][2] += 0.22
    pose["world"][15][2] += 0.40
    pose["world"][14][2] -= 0.18
    pose["world"][16][2] -= 0.28

    controls = calculate_pose_controls(pose)
    assert abs(controls["left_arm"]["ROT_X"]) > 1.0
    assert abs(controls["right_arm"]["ROT_X"]) > 1.0
    assert controls["left_arm"]["BEND_ANGLE_X"] > 0.0
    assert controls["right_arm"]["BEND_ANGLE_X"] > 0.0


def test_torso_and_head_use_their_captured_landmark_axes():
    pose = standing_pose()
    for index in (0, 7, 8, 11, 12):
        pose["world"][index][2] += 0.12
    controls = calculate_pose_controls(pose)
    assert any(abs(controls["body"][field]) > 0.1 for field in ("ROT_X", "ROT_Y", "ROT_Z"))
    assert any(abs(controls["head"][field]) > 0.1 for field in ("ROT_X", "ROT_Y", "ROT_Z"))


def test_slow_subtle_motion_keeps_keyframes():
    frames = [{"ROT_X": index * 0.05} for index in range(16)]
    selected = _select_keyframes(frames, ("ROT_X",), fps=30, optimize=True)
    assert len(selected) >= 4
    assert selected[0] == 0
    assert selected[-1] == 15
    assert max(b - a for a, b in zip(selected, selected[1:])) <= 6


def test_export_animates_only_body_parts_and_never_moves_the_character(tmp_path):
    template_path = tmp_path / "template.miobject"
    output_path = tmp_path / "captured.miobject"
    make_template(template_path)

    pose_a = standing_pose()
    pose_b = standing_pose()
    pose_b["world"][25][0] -= 0.16
    pose_b["world"][27][0] -= 0.30
    pose_b["world"][26][0] += 0.14
    pose_b["world"][28][0] += 0.27
    samples = [(0.0, pose_a), (0.5, pose_b), (1.0, pose_a)]

    result = export_miobject(
        template_path,
        output_path,
        samples,
        fps=30,
        duration_seconds=1.0,
        optimize_keyframes=False,
        smooth_motion=False,
    )

    exported = json.loads(output_path.read_text(encoding="utf-8"))
    character = next(item for item in exported["timelines"] if item["type"] == "char")
    assert character["default_values"] == {
        "POS_X": 12.0, "POS_Y": 24.0, "POS_Z": 3.0
    }
    assert character["keyframes"] == {
        "0": {"POS_X": 12.0, "POS_Y": 24.0, "POS_Z": 3.0, "ROT_Z": 0.0}
    }

    for part in ("body", "head", "left_arm", "right_arm", "left_leg", "right_leg"):
        timeline = next(
            item for item in exported["timelines"]
            if item.get("model_part_name") == part
        )
        assert len(timeline["keyframes"]) == 31
        assert "POS_X" not in timeline["keyframes"]["0"]
        assert "POS_Y" not in timeline["keyframes"]["0"]

    left_leg = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "left_leg"
    )
    right_leg = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "right_leg"
    )
    assert any(abs(frame["ROT_X"]) + abs(frame["ROT_Z"]) > 1.0
               for frame in left_leg["keyframes"].values())
    assert any(abs(frame["ROT_X"]) + abs(frame["ROT_Z"]) > 1.0
               for frame in right_leg["keyframes"].values())
    assert next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "left_arm"
    )["keyframes"]["0"]["POS_Z"] == -0.53
    assert next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "right_arm"
    )["keyframes"]["0"]["POS_Z"] == -0.43

    assert result["keyframe_counts"] == {
        "body": 31,
        "head": 31,
        "left_arm": 31,
        "right_arm": 31,
        "left_leg": 31,
        "right_leg": 31,
    }
    assert result["total_keyframes"] == 6 * 31


def test_export_preserves_static_rig_properties_and_accessories(tmp_path):
    template_path = tmp_path / "template.miobject"
    output_path = tmp_path / "captured.miobject"
    make_template(template_path)
    pose = standing_pose()

    export_miobject(
        template_path,
        output_path,
        [(0.0, pose), (1.0, pose)],
        fps=30,
        duration_seconds=1.0,
        optimize_keyframes=False,
        smooth_motion=False,
    )

    exported = json.loads(output_path.read_text(encoding="utf-8"))
    head = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "head"
    )
    left_arm = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "left_arm"
    )
    right_arm = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "right_arm"
    )
    hat = next(
        item for item in exported["timelines"]
        if item.get("model_part_name") == "hat"
    )
    assert head["keyframes"]["0"]["TEXTURE_OBJ"] == "GREGOR_HEAD_TEXTURE"
    assert left_arm["keyframes"]["0"]["POS_Z"] == -0.53
    assert right_arm["keyframes"]["0"]["POS_Z"] == -0.43
    assert hat["keyframes"] == {}


def test_export_rejects_empty_capture(tmp_path):
    template_path = tmp_path / "template.miobject"
    make_template(template_path)
    with pytest.raises(MiobjectError):
        export_miobject(
            template_path,
            tmp_path / "out.miobject",
            [],
            fps=30,
        )



def test_head_and_torso_follow_their_own_landmark_changes():
    neutral = standing_pose()
    moved = standing_pose()
    moved["world"][11][2] += 0.12
    moved["world"][12][2] += 0.12
    moved["world"][0][1] += 0.08
    moved["world"][7][2] -= 0.12
    moved["world"][8][2] += 0.12

    original = calculate_pose_controls(neutral)
    controls = calculate_pose_controls(moved)
    assert abs(controls["body"]["ROT_X"] - original["body"]["ROT_X"]) > 1.0
    assert (
        abs(controls["head"]["ROT_X"] - original["head"]["ROT_X"]) > 1.0
        or abs(controls["head"]["ROT_Y"] - original["head"]["ROT_Y"]) > 1.0
        or abs(controls["head"]["ROT_Z"] - original["head"]["ROT_Z"]) > 1.0
    )
